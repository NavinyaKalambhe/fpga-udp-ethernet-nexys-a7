def idx(ch):
    return ord(ch) - 0x20

def font_rom_v():
    lines = ["// font_rom.v - 5x7 font in 8x8 cells, GENERATED by scripts/gen_display.py (do not edit)",
             "// idx = ASCII - 0x20 (0..63); bit 7 of `bits` is the leftmost pixel.",
             "module font_rom (",
             "    input      [5:0] idx,",
             "    input      [2:0] row,",
             "    output reg [7:0] bits",
             ");",
             "    always @* begin",
             "        case ({idx, row})"]
    for ch in sorted(G, key=idx):
        if ch == " ":
            continue
        for r, pat in enumerate(G[ch]):
            val = int("".join("1" if c == "#" else "0" for c in pat) + "000", 2)
            if val:
                lines.append(f"            9'd{idx(ch) * 8 + r}: bits = 8'h{val:02X};   // '{ch}' row {r}")
    lines += ["            default: bits = 8'h00;", "        endcase", "    end", "endmodule", ""]
    return "\n".join(lines)

# ----------------------------------------------------------------------------- screen layout
COLS, ROWS = 40, 30
static = []     # (row, col, text)
dyn = []        # (row, col, kind, signal)
def T(r, c, s): static.append((r, c, s))

T(1, 5,  "NEXYS A7  UDP / ETHERNET NODE")
T(2, 3,  "10/100 RMII  LAN8720A  VGA 640X480")
T(4, 2,  "MAC  02:A7:00:00:00:01")
T(5, 2,  "IP   192.168.1.10")
T(6, 2,  "UDP  ECHO 7777   TEXT 5005")
T(8, 2,  "COUNTERS (HEX)")
for r, (label, sig) in enumerate([("FRAMES RX", "st_rx_frames"), ("FRAMES TX", "st_tx_frames"),
                                  ("CRC ERRORS", "st_crc_err"), ("OVERRUN", "st_overrun"),
                                  ("ARP REPLIES", "st_arp"), ("PING REPLIES", "st_icmp"),
                                  ("UDP ECHOES", "st_udp"), ("IGNORED", "st_ignored")], start=9):
    T(r, 2, label)
    dyn.append((r, 16, "hex32", sig))
T(18, 2, "LAST SOURCE IP")
dyn.append((18, 18, "ip", "last_ip"))
T(19, 2, "LAST UDP PORT")
dyn.append((19, 18, "dec16", "last_port"))
T(20, 2, "LAST LENGTH")
dyn.append((20, 18, "dec16", "last_len"))
T(22, 2, "TEXT MESSAGE (UDP PORT 5005)")
dyn.append((23, 2, "msg", "msg_bytes"))
T(25, 2, "LAST FRAME, FIRST 32 BYTES (HEX)")
for r, (first, n) in zip((26, 27, 28), ((0, 12), (12, 12), (24, 8))):
    dyn.append((r, 2, f"hexbytes:{first}:{n}", "dump_bytes"))
T(29, 2, "TRY: PING 192.168.1.10")

SIGNALS = [("st_rx_frames", 32), ("st_tx_frames", 32), ("st_crc_err", 32), ("st_overrun", 32),
           ("st_arp", 32), ("st_icmp", 32), ("st_udp", 32), ("st_ignored", 32),
           ("last_ip", 32), ("last_port", 16), ("last_len", 16), ("msg_bytes", 256), ("dump_bytes", 256)]

def status_writer_v():
    # slot = (text RAM address, kind, 8-bit raw value expression, blank expression)
    #   kind 0 = static char index, 1 = hex nibble, 2 = ASCII byte, 3 = decimal digit
    slots = []
    for r, c, s_ in static:
        for i, ch in enumerate(s_):
            assert ch in G, f"no glyph for {ch!r}"
            if ch != " ":
                slots.append((r * COLS + c + i, 0, f"8'd{idx(ch)}", "1'b0"))
    for r, c, kind, sig in dyn:
        base = r * COLS + c
        if kind == "hex32":
            for n in range(8):
                slots.append((base + n, 1, f"{{4'd0, {sig}[{4 * (7 - n) + 3}:{4 * (7 - n)}]}}", "1'b0"))
        elif kind == "ip":
            pos = 0
            for b in range(4):
                for d in "htu":
                    slots.append((base + pos, 3, f"{{4'd0, {sig}_b{b}_{d}}}", f"{sig}_b{b}_{d}_blank")); pos += 1
                if b < 3:
                    slots.append((base + pos, 0, f"8'd{idx('.')}", "1'b0")); pos += 1
        elif kind == "dec16":
            for n in range(5):
                slots.append((base + n, 3, f"{{4'd0, {sig}_d{n}}}", f"{sig}_d{n}_blank"))
        elif kind == "msg":
            for n in range(32):
                slots.append((base + n, 2, f"{sig}[{255 - 8 * n}:{248 - 8 * n}]", "1'b0"))
        elif kind.startswith("hexbytes"):
            _, first, cnt = kind.split(":")
            pos = 0
            for b in range(int(first), int(first) + int(cnt)):
                hi = 255 - 8 * b
                slots.append((base + pos, 1, f"{{4'd0, {sig}[{hi}:{hi - 3}]}}", "1'b0"))
                slots.append((base + pos + 1, 1, f"{{4'd0, {sig}[{hi - 4}:{hi - 7}]}}", "1'b0"))
                pos += 3
    assert len(slots) < 1024, len(slots)

    L = []
    L.append("// status_writer.v - walks the screen layout and writes one character per clock into the")
    L.append("// VGA text RAM. GENERATED by scripts/gen_display.py (do not edit; edit the layout there).")
    L.append("// Each slot selects a raw value (static char, hex nibble, ASCII byte or decimal digit);")
    L.append("// the conversion to a font index is done ONCE after the selection.")
    L.append("module status_writer (")
    L.append("    input         clk,")
    for name, w in SIGNALS:
        L.append(f"    input  [{w - 1}:0] {name},")
    L.append("    output reg        tw_en,")
    L.append("    output reg [10:0] tw_addr,")
    L.append("    output reg [5:0]  tw_data")
    L.append(");")
    L.append(f"    localparam integer NSLOT = {len(slots)};")
    # binary -> BCD (shift-and-add-3), no dividers
    L.append("""
    function [19:0] bcd16(input [15:0] bin);          // 5 BCD digits
        integer i;
        reg [35:0] z;
        begin
            z = {20'd0, bin};
            for (i = 0; i < 16; i = i + 1) begin
                if (z[19:16] >= 4'd5) z[19:16] = z[19:16] + 4'd3;
                if (z[23:20] >= 4'd5) z[23:20] = z[23:20] + 4'd3;
                if (z[27:24] >= 4'd5) z[27:24] = z[27:24] + 4'd3;
                if (z[31:28] >= 4'd5) z[31:28] = z[31:28] + 4'd3;
                if (z[35:32] >= 4'd5) z[35:32] = z[35:32] + 4'd3;
                z = z << 1;
            end
            bcd16 = z[35:16];
        end
    endfunction

    function [11:0] bcd8(input [7:0] bin);            // 3 BCD digits
        integer i;
        reg [19:0] z;
        begin
            z = {12'd0, bin};
            for (i = 0; i < 8; i = i + 1) begin
                if (z[11:8]  >= 4'd5) z[11:8]  = z[11:8]  + 4'd3;
                if (z[15:12] >= 4'd5) z[15:12] = z[15:12] + 4'd3;
                if (z[19:16] >= 4'd5) z[19:16] = z[19:16] + 4'd3;
                z = z << 1;
            end
            bcd8 = z[19:8];
        end
    endfunction
""")
    for name, w in SIGNALS:
        if name == "last_ip":
            for b in range(4):
                L.append(f"    wire [11:0] {name}_b{b}_bcd = bcd8(last_ip[{31 - 8 * b}:{24 - 8 * b}]);")
                L.append(f"    wire [3:0] {name}_b{b}_h = {name}_b{b}_bcd[11:8];")
                L.append(f"    wire [3:0] {name}_b{b}_t = {name}_b{b}_bcd[7:4];")
                L.append(f"    wire [3:0] {name}_b{b}_u = {name}_b{b}_bcd[3:0];")
                L.append(f"    wire {name}_b{b}_h_blank = ({name}_b{b}_h == 4'd0);")
                L.append(f"    wire {name}_b{b}_t_blank = {name}_b{b}_h_blank && ({name}_b{b}_t == 4'd0);")
                L.append(f"    wire {name}_b{b}_u_blank = 1'b0;")
        elif name in ("last_port", "last_len"):
            L.append(f"    wire [19:0] {name}_bcd = bcd16({name});")
            for n in range(5):
                L.append(f"    wire [3:0] {name}_d{n} = {name}_bcd[{19 - 4 * n}:{16 - 4 * n}];")
            L.append(f"    wire {name}_d0_blank = ({name}_d0 == 4'd0);")
            L.append(f"    wire {name}_d1_blank = {name}_d0_blank && ({name}_d1 == 4'd0);")
            L.append(f"    wire {name}_d2_blank = {name}_d1_blank && ({name}_d2 == 4'd0);")
            L.append(f"    wire {name}_d3_blank = {name}_d2_blank && ({name}_d3 == 4'd0);")
            L.append(f"    wire {name}_d4_blank = 1'b0;")
    L.append("""
    reg [9:0]  slot = 10'd0;
    reg [10:0] a;
    reg [1:0]  kind;
    reg [7:0]  v;
    reg        blank;

    always @* begin
        a = 11'd0; kind = 2'd0; v = 8'd0; blank = 1'b0;
        case (slot)""")
    for i, (addr, kind, val, blank) in enumerate(slots):
        L.append(f"            10'd{i}: begin a = 11'd{addr}; kind = 2'd{kind}; v = {val}; blank = {blank}; end")
    L.append("""            default: ;
        endcase
    end

    // single conversion of the selected raw value to a 6-bit font index (ASCII - 0x20)
    reg [5:0] d;
    reg [7:0] u;
    always @* begin
        u = (v >= 8'h61 && v <= 8'h7A) ? (v - 8'h20) : v;           // ASCII: lower -> upper case
        case (kind)
            2'd0:    d = v[5:0];                                                       // static
            2'd1:    d = (v[3:0] < 4'd10) ? (6'd16 + {2'd0, v[3:0]}) : (6'd23 + {2'd0, v[3:0]});   // hex: '0'-'9','A'-'F'
            2'd2:    d = (u >= 8'h20 && u <= 8'h5F) ? (u[5:0] - 6'd32 + 6'd0) : 6'd14;            // ASCII, others '.'
            default: d = blank ? 6'd0 : (6'd16 + {2'd0, v[3:0]});                      // decimal digit
        endcase
    end

    always @(posedge clk) begin
        tw_en   <= 1'b1;
        tw_addr <= a;
        tw_data <= d;
        slot    <= (slot == NSLOT - 1) ? 10'd0 : slot + 10'd1;
    end
endmodule
""")
    return "\n".join(L)

# ----------------------------------------------------------------------------- preview (ASCII)
def preview():
    scr = [[" "] * COLS for _ in range(ROWS)]
    for r, c, s in static:
        for i, ch in enumerate(s):
            scr[r][c + i] = ch
    for r, c, kind, sig in dyn:
        w = {"hex32": 8, "ip": 15, "dec16": 5, "msg": 32}.get(kind, 35 if kind.startswith("hexbytes") else 0)
        for i in range(w):
            scr[r][c + i] = "#"
    return "\n".join("".join(row) for row in scr)

if __name__ == "__main__":
    open("rtl/font_rom.v", "w").write(font_rom_v())
    open("rtl/status_writer.v", "w").write(status_writer_v())
    print("wrote rtl/font_rom.v and rtl/status_writer.v")
    print(preview())
